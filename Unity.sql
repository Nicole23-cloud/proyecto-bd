CREATE DATABASE UNITY_MIRAFLORES
USE UNITY_MIRAFLORES
GO

CREATE SCHEMA PREVENTA; 
GO
CREATE SCHEMA VENTA ;
GO
CREATE SCHEMA POSTVENTA;
GO
CREATE SCHEMA LOGISTICA;
GO
CREATE SCHEMA CONTABILIDAD;
GO

---PREVENTA

CREATE TABLE PREVENTA.REQUERIMIENTO (
    ID_REQUERIMIENTO INT PRIMARY KEY,
    DESCRIPCION VARCHAR(500),
    FECHA_SOLICITUD DATE,
    ESTADO VARCHAR(30)
);

CREATE TABLE PREVENTA.CARPETA (
    ID_CARPETA INT PRIMARY KEY,
    ID_REQUERIMIENTO INT FOREIGN KEY REFERENCES PREVENTA.REQUERIMIENTO(ID_REQUERIMIENTO),
    RUC CHAR(11),
    RAZON_SOCIAL VARCHAR(150),
    DESCRIPCION VARCHAR(500),
    FECHA_CREACION DATE,
    PROPUESTA VARCHAR(500),
    ESTADO VARCHAR(30)
);

---LOGÍSTICA

CREATE TABLE LOGISTICA.PRODUCTO (
    ID_PRODUCTO INT PRIMARY KEY,
    NOMBRE VARCHAR(150),
    DESCRIPCIÓN VARCHAR(100),
    CATEGORIA VARCHAR(50),
    TIPO_PRODUCTO VARCHAR(20),
    MARCA VARCHAR (20),
    ESTADO VARCHAR (20),
    PRECIO DECIMAL(10,2)
);

CREATE TABLE LOGISTICA.ALMACEN (
    ID_FORMULA INT PRIMARY KEY,
    ID_PRODUCTO INT FOREIGN KEY REFERENCES LOGISTICA.PRODUCTO(ID_PRODUCTO),
    CANTIDAD_TIPOUNIDAD INT,
    TIPO_UNIDAD VARCHAR(30),
    UNIDADES INT,
    OBSERVACIONES VARCHAR(20),   
);

CREATE TABLE LOGISTICA.PROVEEDOR (
    RUC CHAR(11) PRIMARY KEY,
    RAZON_SOCIAL VARCHAR(150),
    TELEFONO VARCHAR(20),
    CORREO VARCHAR(100),
    DIRECCION VARCHAR(200)
);

CREATE TABLE LOGISTICA.ENTRADA (
    ID_ENTRADA INT PRIMARY KEY,
    RUC_PROVEEDOR CHAR(11) FOREIGN KEY REFERENCES LOGISTICA.PROVEEDOR(RUC),
    FECHA DATE
);

CREATE TABLE LOGISTICA.DETALLE_ENTRADA (
    ID_DETALLE INT PRIMARY KEY,
    ID_ENTRADA INT FOREIGN KEY REFERENCES LOGISTICA.ENTRADA(ID_ENTRADA),
    ID_PRODUCTO INT FOREIGN KEY REFERENCES LOGISTICA.PRODUCTO(ID_PRODUCTO),
    CANTIDAD INT
);

CREATE TABLE LOGISTICA.SALIDA (
    ID_SALIDA INT PRIMARY KEY,
    FECHA DATE,
    MOTIVO VARCHAR(100)
);

CREATE TABLE LOGISTICA.DETALLE_SALIDA (
    ID_DETALLE INT PRIMARY KEY,
    ID_SALIDA INT FOREIGN KEY REFERENCES LOGISTICA.SALIDA(ID_SALIDA),
    ID_PRODUCTO INT FOREIGN KEY REFERENCES LOGISTICA.PRODUCTO(ID_PRODUCTO),
    CANTIDAD INT
);

---VENTA
CREATE TABLE VENTA.CLIENTE (
    RUC CHAR(11) PRIMARY KEY,
    RAZON_SOCIAL VARCHAR(150),
    TELEFONO VARCHAR(20),
    CORREO VARCHAR(100),
    DIRECCION VARCHAR(200)
);

CREATE TABLE VENTA.CONTACTO_CLIENTE (
    ID_CONTACTO INT PRIMARY KEY,
    RUC CHAR(11) FOREIGN KEY REFERENCES VENTA.CLIENTE(RUC),
    NOMBRE VARCHAR(100),
    APELLIDO VARCHAR(100),
    CARGO VARCHAR(100),
    TELEFONO VARCHAR(20),
    CORREO VARCHAR(100)
);

CREATE TABLE VENTA.VENTA (
    ID_VENTA INT PRIMARY KEY,
    RUC CHAR(11) FOREIGN KEY REFERENCES VENTA.CLIENTE(RUC),
    FECHA DATE,
    TOTAL DECIMAL(10,2),
    ESTADO VARCHAR(30)
);

CREATE TABLE VENTA.DETALLE_VENTA (
    ID_DETALLE INT PRIMARY KEY,
    ID_VENTA INT FOREIGN KEY REFERENCES VENTA.VENTA(ID_VENTA),
    ID_PRODUCTO INT FOREIGN KEY REFERENCES LOGISTICA.PRODUCTO(ID_PRODUCTO),
    CANTIDAD INT,
    PRECIO_UNITARIO DECIMAL(10,2),
    SUBTOTAL DECIMAL(10,2)
);

---POSTVENTA

CREATE TABLE POSTVENTA.ATENCION (
    ID_ATENCION INT PRIMARY KEY,
    ID_VENTA INT FOREIGN KEY REFERENCES VENTA.VENTA(ID_VENTA),
    ID_CONTACTO INT FOREIGN KEY REFERENCES VENTA.CONTACTO_CLIENTE(ID_CONTACTO),
    FECHA DATE,
    TIPO VARCHAR(30),
    DESCRIPCION VARCHAR(500),
    ESTADO VARCHAR(30)
);

CREATE TABLE POSTVENTA.GARANTIA (
    ID_GARANTIA INT PRIMARY KEY,
    ID_ATENCION INT FOREIGN KEY REFERENCES POSTVENTA.ATENCION(ID_ATENCION),
    ID_PRODUCTO INT FOREIGN KEY REFERENCES LOGISTICA.PRODUCTO(ID_PRODUCTO),
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    ESTADO VARCHAR(30)
);

CREATE TABLE POSTVENTA.MANTENIMIENTO (
    ID_MANTENIMIENTO INT PRIMARY KEY,
    ID_ATENCION INT FOREIGN KEY REFERENCES POSTVENTA.ATENCION(ID_ATENCION),
    ID_PRODUCTO INT FOREIGN KEY REFERENCES LOGISTICA.PRODUCTO(ID_PRODUCTO),
    FECHA_PROGRAMADA DATE,
    FECHA_REALIZADA DATE,
    DESCRIPCION VARCHAR(500),
    ESTADO VARCHAR(30)
);

--CONTABILIDAD

CREATE TABLE CONTABILIDAD.FACTURA (
    ID_FACTURA INT PRIMARY KEY,
    ID_VENTA INT FOREIGN KEY REFERENCES VENTA.VENTA(ID_VENTA),
    FECHA_EMISION DATE,
    TIPO_COMPROBANTE VARCHAR(30),
    NUMERO_COMPROBANTE VARCHAR(30),
    TOTAL DECIMAL(10,2)
);

CREATE TABLE CONTABILIDAD.PAGO (
    ID_PAGO INT PRIMARY KEY,
    ID_FACTURA INT FOREIGN KEY REFERENCES CONTABILIDAD.FACTURA(ID_FACTURA),
    FECHA_PAGO DATE,
    MONTO DECIMAL(10,2),
    METODO_PAGO VARCHAR(30)
);

CREATE TABLE CONTABILIDAD.GASTO (
    ID_GASTO INT PRIMARY KEY,
    DESCRIPCION VARCHAR(300),
    FECHA DATE,
    MONTO DECIMAL(10,2)
);

CREATE TABLE CONTABILIDAD.COSTO (
    ID_COSTO INT PRIMARY KEY,
    ID_PRODUCTO INT FOREIGN KEY REFERENCES LOGISTICA.PRODUCTO(ID_PRODUCTO),
    DESCRIPCION VARCHAR(300),
    MONTO DECIMAL(10,2),
    FECHA DATE
);

